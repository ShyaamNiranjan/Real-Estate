# Creates the local Scrollwalk databases (scrollwalk_dev, scrollwalk_test) and the four
# database roles, then writes their connection strings to backend/.env (gitignored).
# Asks for the postgres superuser password; it is never stored. Safe to re-run: existing
# role passwords in backend/.env are reused.

param(
  [string]$PsqlPath = "D:\PostgreSQL\bin\psql.exe",
  [string]$DbHost = "localhost",
  [int]$Port = 5432,
  [string]$Superuser = "postgres"
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$envFile = Join-Path $root "backend\.env"
$sql = Join-Path $root "backend\db\bootstrap.sql"

function New-Secret {
  $bytes = New-Object byte[] 32
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  -join ($bytes | ForEach-Object { $_.ToString("x2") })
}

$existing = @{}
$otherLines = @()
if (Test-Path $envFile) {
  Get-Content $envFile | ForEach-Object {
    if ($_ -match '^(DB_\w+_PASSWORD)=(.+)$') { $existing[$Matches[1]] = $Matches[2] }
    elseif ($_ -match '^(SECRET_KEY)=(.+)$') { $existing[$Matches[1]] = $Matches[2] }
    elseif ($_ -match '^[A-Z_]+=' -and $_ -notmatch '^(TEST_)?(MIGRATIONS_|PUBLIC_|HQ_)?DATABASE_URL=') { $otherLines += $_ }
  }
}
$secretKey = if ($existing["SECRET_KEY"]) { $existing["SECRET_KEY"] } else { New-Secret }
$pw = @{}
foreach ($k in "OWNER", "RW", "PUBLIC", "HQ") {
  $key = "DB_${k}_PASSWORD"
  $pw[$k] = if ($existing[$key]) { $existing[$key] } else { New-Secret }
}

$secure = Read-Host "Password for PostgreSQL user '$Superuser'" -AsSecureString
$env:PGPASSWORD = [Runtime.InteropServices.Marshal]::PtrToStringAuto(
  [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure))

try {
  & $PsqlPath -h $DbHost -p $Port -U $Superuser -d postgres -X -q `
    -v "owner_pw=$($pw.OWNER)" -v "rw_pw=$($pw.RW)" -v "public_pw=$($pw.PUBLIC)" -v "hq_pw=$($pw.HQ)" `
    -f $sql
  if ($LASTEXITCODE -ne 0) { throw "psql failed with exit code $LASTEXITCODE" }
} finally {
  Remove-Item Env:PGPASSWORD -ErrorAction SilentlyContinue
}

function Url($user, $pass, $db) { "postgresql+psycopg://${user}:${pass}@${DbHost}:${Port}/${db}" }

$lines = @(
  "# Local development only. Generated by scripts/db-bootstrap.ps1. Never commit.",
  "DB_OWNER_PASSWORD=$($pw.OWNER)",
  "DB_RW_PASSWORD=$($pw.RW)",
  "DB_PUBLIC_PASSWORD=$($pw.PUBLIC)",
  "DB_HQ_PASSWORD=$($pw.HQ)",
  "",
  "MIGRATIONS_DATABASE_URL=$(Url 'app_owner' $pw.OWNER 'scrollwalk_dev')",
  "DATABASE_URL=$(Url 'app_rw' $pw.RW 'scrollwalk_dev')",
  "PUBLIC_DATABASE_URL=$(Url 'app_public' $pw.PUBLIC 'scrollwalk_dev')",
  "HQ_DATABASE_URL=$(Url 'app_hq' $pw.HQ 'scrollwalk_dev')",
  "",
  "TEST_MIGRATIONS_DATABASE_URL=$(Url 'app_owner' $pw.OWNER 'scrollwalk_test')",
  "TEST_DATABASE_URL=$(Url 'app_rw' $pw.RW 'scrollwalk_test')",
  "TEST_PUBLIC_DATABASE_URL=$(Url 'app_public' $pw.PUBLIC 'scrollwalk_test')",
  "TEST_HQ_DATABASE_URL=$(Url 'app_hq' $pw.HQ 'scrollwalk_test')",
  "",
  "SECRET_KEY=$secretKey"
) + $otherLines
New-Item -ItemType Directory -Force -Path (Split-Path $envFile) | Out-Null
Set-Content -Path $envFile -Value $lines -Encoding utf8

Write-Host ""
Write-Host "Created scrollwalk_dev and scrollwalk_test with roles app_owner, app_rw, app_public, app_hq." -ForegroundColor Green
Write-Host "Connection strings written to backend\.env"
